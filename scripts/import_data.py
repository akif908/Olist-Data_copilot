"""Create the Phase 1 schema and import the selected Olist CSVs into PostgreSQL.

Steps:
1. Execute db/schema.sql (DDL, idempotent CREATE TABLE IF NOT EXISTS).
2. Load each selected CSV with PostgreSQL COPY (server-side casting to the
   declared column types; unquoted empty fields become NULL).
3. Verify: row counts vs source files, FK orphan checks, column types.

Safety:
- Refuses to load into non-empty tables unless --replace is passed explicitly.
- Credentials come from .env (app.config); nothing sensitive is printed.

Usage:
    python -m scripts.import_data            # first load (tables must be empty)
    python -m scripts.import_data --replace  # TRUNCATE selected tables, reload
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
import psycopg

from app.config import DATA_DIR, PROJECT_ROOT
from app.database.connection import get_connection

SCHEMA_PATH = PROJECT_ROOT / "db" / "schema.sql"
REPORT_PATH = PROJECT_ROOT / "docs" / "import_verification.md"

# Load order respects foreign keys. seller_id in order_items is intentionally
# loaded without an FK until the sellers table is imported (documented).
TABLE_LOADS: list[tuple[str, str]] = [
    ("customers", "olist_customers_dataset.csv"),
    ("orders", "olist_orders_dataset.csv"),
    ("product_category_translation", "product_category_name_translation.csv"),
    ("products", "olist_products_dataset.csv"),
    ("order_items", "olist_order_items_dataset.csv"),
    ("order_payments", "olist_order_payments_dataset.csv"),
    ("order_reviews", "olist_order_reviews_dataset.csv"),
]

# (child table, child cols, parent table, parent cols) verified after loading.
# These correspond to ENFORCED foreign keys and must have zero orphans.
FK_CHECKS: list[tuple[str, list[str], str, list[str]]] = [
    ("orders", ["customer_id"], "customers", ["customer_id"]),
    ("order_items", ["order_id"], "orders", ["order_id"]),
    ("order_items", ["product_id"], "products", ["product_id"]),
    ("order_payments", ["order_id"], "orders", ["order_id"]),
    ("order_reviews", ["order_id"], "orders", ["order_id"]),
]

# Informational lookup-coverage checks (no enforced FK; orphans are expected
# and documented in docs/schema.md — they do not fail the import).
LOOKUP_CHECKS: list[tuple[str, list[str], str, list[str]]] = [
    ("products", ["product_category_name"],
     "product_category_translation", ["product_category_name"]),
]


def csv_columns(path: Path) -> list[str]:
    return list(pd.read_csv(path, nrows=0).columns)


def csv_row_count(path: Path) -> int:
    return len(pd.read_csv(path, usecols=[0]))


def create_schema(conn: psycopg.Connection) -> None:
    conn.execute(SCHEMA_PATH.read_text(encoding="utf-8"))
    conn.commit()


def tables_to_load(conn: psycopg.Connection) -> list[tuple[str, str]]:
    """Non-destructive default: only load tables that are currently empty.

    Tables that already contain rows are skipped with a notice, so adding a
    new table to TABLE_LOADS never touches existing data.
    """
    todo: list[tuple[str, str]] = []
    for table, filename in TABLE_LOADS:
        n = conn.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
        if n:
            print(f"Skipping {table}: already has {n} rows (use --replace to reload).")
        else:
            todo.append((table, filename))
    return todo


def truncate_tables(conn: psycopg.Connection) -> None:
    names = ", ".join(t for t, _ in TABLE_LOADS)
    conn.execute(f"TRUNCATE {names} CASCADE")
    conn.commit()


def copy_csv(conn: psycopg.Connection, table: str, path: Path) -> None:
    cols = csv_columns(path)
    col_list = ", ".join(f'"{c}"' for c in cols)
    stmt = f"COPY {table} ({col_list}) FROM STDIN WITH (FORMAT csv, HEADER true, NULL '')"
    with path.open("rb") as f, conn.cursor() as cur:
        with cur.copy(stmt) as copy:
            while chunk := f.read(1 << 20):
                copy.write(chunk)
    conn.commit()


def _orphan_count_sql(
    conn: psycopg.Connection,
    child: str, ccols: list[str], parent: str, pcols: list[str],
) -> int:
    """Count child rows whose non-NULL key has no match in parent."""
    q = (
        f"SELECT count(*) FROM {child} c LEFT JOIN {parent} p "
        f"ON ({' AND '.join(f'c.{a} = p.{b}' for a, b in zip(ccols, pcols))}) "
        f"WHERE c.{ccols[0]} IS NOT NULL AND p.{pcols[0]} IS NULL"
    )
    return conn.execute(q).fetchone()[0]


def verify(conn: psycopg.Connection) -> list[str]:
    lines = [
        "# Phase 1 — Import Verification",
        "",
        "Generated by `python -m scripts.import_data`.",
        "",
        "## Row counts (PostgreSQL vs source CSV)",
        "",
        "| Table | DB rows | CSV rows | Match |",
        "|---|---:|---:|---|",
    ]
    all_ok = True
    for table, filename in TABLE_LOADS:
        db_n = conn.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
        csv_n = csv_row_count(DATA_DIR / filename)
        ok = db_n == csv_n
        all_ok &= ok
        lines.append(f"| `{table}` | {db_n} | {csv_n} | {'OK' if ok else 'MISMATCH'} |")

    lines += ["", "## Foreign-key orphan checks (enforced FKs)", "",
              "| Child | Parent | Orphans | Verdict |", "|---|---|---:|---|"]
    for child, ccols, parent, pcols in FK_CHECKS:
        n = _orphan_count_sql(conn, child, ccols, parent, pcols)
        all_ok &= n == 0
        lines.append(
            f"| `{child}` ({', '.join(ccols)}) | `{parent}` ({', '.join(pcols)}) "
            f"| {n} | {'OK' if n == 0 else 'FAIL'} |"
        )

    lines += ["", "## Lookup coverage (informational — no enforced FK)", "",
              "| Child | Lookup | Unmatched rows | Note |", "|---|---|---:|---|"]
    for child, ccols, parent, pcols in LOOKUP_CHECKS:
        n = _orphan_count_sql(conn, child, ccols, parent, pcols)
        lines.append(
            f"| `{child}` ({', '.join(ccols)}) | `{parent}` | {n} "
            "| Expected: 13 products in 2 categories missing from translation "
            "(pc_gamer, portateis_cozinha_e_preparadores_de_alimentos). Use LEFT JOIN. |"
        )

    lines += ["", "## Column types (information_schema)", ""]
    for table, _ in TABLE_LOADS:
        rows = conn.execute(
            "SELECT column_name, data_type, is_nullable FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = %s ORDER BY ordinal_position",
            (table,),
        ).fetchall()
        lines += [f"### `{table}`", "",
                  "| Column | Type | Nullable |", "|---|---|---|"]
        lines += [f"| `{c}` | {t} | {n} |" for c, t, n in rows]
        lines.append("")

    lines += ["## Result", "",
              "ALL CHECKS PASSED" if all_ok else "CHECKS FAILED — see tables above", ""]
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replace", action="store_true",
                        help="TRUNCATE the selected tables before loading (destructive)")
    args = parser.parse_args()

    with get_connection() as conn:
        create_schema(conn)
        print("Schema created (CREATE TABLE IF NOT EXISTS).")
        if args.replace:
            truncate_tables(conn)
            print("Existing rows truncated (--replace).")
            loads = TABLE_LOADS
        else:
            loads = tables_to_load(conn)

        for table, filename in loads:
            path = DATA_DIR / filename
            copy_csv(conn, table, path)
            n = conn.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
            print(f"Loaded {table}: {n} rows")

        lines = verify(conn)

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Verification report: {REPORT_PATH}")
    print(lines[-2])


if __name__ == "__main__":
    main()