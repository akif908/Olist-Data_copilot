"""Evaluate retrieval quality and compare embedding providers (Phase 4).

Runs the manually verified question set in knowledge_base/eval/retrieval_questions.json
against each configured embedding provider, computing:

* Recall@K — fraction of ground-truth relevant chunks found in the top-K
* Hit@K    — fraction of questions with >=1 relevant chunk in the top-K
* MRR      — mean reciprocal rank of the first relevant chunk

Each provider is ingested into its OWN eval collection (no silent model switch),
so OpenRouter and the local sentence-transformer baseline are compared fairly on
identical chunks and questions. Results are written to docs/rag_evaluation.md.

Usage:
    python -m scripts.evaluate_retrieval
    python -m scripts.evaluate_retrieval --providers openrouter
    python -m scripts.evaluate_retrieval --providers openrouter,local --k 1,3,5
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from app.config import PROJECT_ROOT, EmbeddingSettings
from app.rag.embedding_factory import create_embedding_service
from app.rag.embeddings import EmbeddingError
from app.rag.ingestion import CHROMA_DIR, ingest
from app.rag.retriever import Retriever

EVAL_PATH = PROJECT_ROOT / "knowledge_base" / "eval" / "retrieval_questions.json"
REPORT_PATH = PROJECT_ROOT / "docs" / "rag_evaluation.md"


def _settings_for(provider: str, base: EmbeddingSettings) -> EmbeddingSettings:
    if provider == base.provider:
        return base
    # Switching provider: clear the model so the factory uses that provider's
    # default (never reuse another provider's model id).
    return EmbeddingSettings(provider=provider, api_key=base.api_key, model="", base_url="")


def evaluate_provider(
    provider: str,
    questions: list[dict],
    k_values: list[int],
    persist_dir: Path,
) -> dict:
    base = EmbeddingSettings.from_env()
    svc = create_embedding_service(_settings_for(provider, base))
    collection = f"olist_knowledge_eval_{provider}"
    ingest(embedding_service=svc, persist_dir=persist_dir,
           collection_name=collection, reset=True)
    retriever = Retriever(embedding_service=svc, persist_dir=persist_dir,
                          collection_name=collection)
    max_k = max(k_values)

    per_question = []
    for q in questions:
        chunks = retriever.retrieve(q["question"], k=max_k)
        labels = [c.label() for c in chunks]
        relevant = set(q["relevant"])
        recall, hit = {}, {}
        for k in k_values:
            topk = set(labels[:k])
            recall[k] = len(topk & relevant) / len(relevant)
            hit[k] = 1.0 if (topk & relevant) else 0.0
        rr = 0.0
        for rank, lab in enumerate(labels, start=1):
            if lab in relevant:
                rr = 1.0 / rank
                break
        per_question.append({
            "id": q["id"], "question": q["question"], "category": q["category"],
            "relevant": q["relevant"], "retrieved": labels,
            "recall": recall, "hit": hit, "rr": rr,
        })

    n = len(per_question)
    mean_recall = {k: sum(pq["recall"][k] for pq in per_question) / n for k in k_values}
    mean_hit = {k: sum(pq["hit"][k] for pq in per_question) / n for k in k_values}
    mrr = sum(pq["rr"] for pq in per_question) / n
    return {
        "provider": provider, "model": svc.name, "dimension": svc.dimension,
        "collection": collection, "n_questions": n,
        "recall": mean_recall, "hit": mean_hit, "mrr": mrr,
        "per_question": per_question,
    }


def _fmt_pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def write_report(results: list[dict], k_values: list[int], path: Path) -> None:
    lines = ["# Phase 4 — Retrieval Evaluation", ""]
    lines.append("Generated by `python -m scripts.evaluate_retrieval`.")
    lines.append("")
    lines.append("## Method")
    lines.append("")
    n = results[0]["n_questions"] if results else 0
    lines.append(f"- Question set: `knowledge_base/eval/retrieval_questions.json` "
                 f"({n} manually verified, paraphrased Olist questions).")
    lines.append("- Ground truth: hand-curated relevant knowledge chunks per question "
                 "(metric / unsupported_metric / example / schema).")
    lines.append(f"- Metrics: Recall@K, Hit@K for K in {k_values}; MRR over top-{max(k_values)}.")
    lines.append("- Each provider is ingested into its own eval collection over identical "
                 "chunks; cosine similarity; no silent model switch.")
    lines.append("")
    lines.append("## Provider comparison")
    lines.append("")
    header = "| Provider | Model | Dim | " + " | ".join(
        f"Recall@{k} | Hit@{k}" for k in k_values) + " | MRR |"
    sep = "|---|---|---:|" + "---:|---:|" * len(k_values) + "---:|"
    lines.append(header)
    lines.append(sep)
    for r in results:
        cells = " | ".join(
            f"{_fmt_pct(r['recall'][k])} | {_fmt_pct(r['hit'][k])}" for k in k_values)
        lines.append(f"| {r['provider']} | `{r['model']}` | {r['dimension']} | "
                     f"{cells} | {r['mrr']:.3f} |")
    lines.append("")

    for r in results:
        lines.append(f"## Per-question detail — {r['provider']} (`{r['model']}`)")
        lines.append("")
        lines.append(f"| Question | Expected | Top-{max(k_values)} retrieved | Recall@{max(k_values)} | RR |")
        lines.append("|---|---|---|---:|---:|")
        for pq in r["per_question"]:
            expected = ", ".join(pq["relevant"])
            retrieved = ", ".join(pq["retrieved"])
            lines.append(f"| {pq['question']} | {expected} | {retrieved} | "
                         f"{_fmt_pct(pq['recall'][max(k_values)])} | {pq['rr']:.2f} |")
        lines.append("")

    lines.append("## Notes")
    lines.append("")
    lines.append("- Recall@K rewards retrieving ALL relevant chunks; Hit@K rewards "
                 "finding at least one. MRR rewards ranking a relevant chunk first.")
    lines.append("- The local baseline (`all-MiniLM-L6-v2`, 384-dim) is optional and "
                 "requires `pip install -r requirements-baseline.txt`; it is used only "
                 "for comparison, never as a silent fallback in production.")
    lines.append("- Retrieval quality is necessary but not sufficient: Phase 5+ still "
                 "validates and safely executes the generated SQL.")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--providers", default="openrouter,local",
                        help="comma-separated: openrouter,local")
    parser.add_argument("--k", default="1,3,5", help="comma-separated K values")
    parser.add_argument("--persist-dir", default=str(CHROMA_DIR))
    parser.add_argument("--eval", default=str(EVAL_PATH))
    parser.add_argument("--out", default=str(REPORT_PATH))
    args = parser.parse_args()

    k_values = sorted(int(x) for x in args.k.split(","))
    providers = [p.strip() for p in args.providers.split(",") if p.strip()]
    data = json.loads(Path(args.eval).read_text("utf-8"))
    questions = data["questions"]

    results = []
    for provider in providers:
        print(f"Evaluating provider: {provider} ...")
        try:
            r = evaluate_provider(provider, questions, k_values, Path(args.persist_dir))
        except EmbeddingError as exc:
            print(f"  SKIPPED {provider}: {exc}")
            continue
        results.append(r)
        print(f"  model={r['model']} dim={r['dimension']} "
              f"Recall@{max(k_values)}={_fmt_pct(r['recall'][max(k_values)])} "
              f"MRR={r['mrr']:.3f}")

    if not results:
        raise SystemExit("No provider could be evaluated.")

    write_report(results, k_values, Path(args.out))
    print("-" * 60)
    print(f"Report written to {args.out}")
    print()
    print(f"{'Provider':<12}{'Model':<42}{'Dim':>6}" +
          "".join(f"{'R@'+str(k):>9}" for k in k_values) + f"{'MRR':>8}")
    for r in results:
        print(f"{r['provider']:<12}{r['model']:<42}{r['dimension']:>6}" +
              "".join(f"{_fmt_pct(r['recall'][k]):>9}" for k in k_values) +
              f"{r['mrr']:>8.3f}")


if __name__ == "__main__":
    main()