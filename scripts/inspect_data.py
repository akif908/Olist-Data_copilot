"""Profile the raw Olist CSV files and write docs/data_inspection.md.

Facts gathered per file: shape, column dtypes, null counts, distinct counts,
duplicate rows, candidate primary keys, and sample values. Relationship
candidates are checked with anti-joins (orphan counts). No database access is
required — this runs entirely on the CSVs in data/.

Usage:
    python -m scripts.inspect_data
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd

from app.config import DATA_DIR, PROJECT_ROOT

REPORT_PATH = PROJECT_ROOT / "docs" / "data_inspection.md"

# Expected source files (Kaggle: Brazilian E-Commerce Public Dataset by Olist).
CSV_FILES = [
    "olist_customers_dataset.csv",
    "olist_orders_dataset.csv",
    "olist_order_items_dataset.csv",
    "olist_order_payments_dataset.csv",
    "olist_order_reviews_dataset.csv",
    "olist_products_dataset.csv",
    "olist_sellers_dataset.csv",
    "olist_geolocation_dataset.csv",
    "product_category_name_translation.csv",
]

# (child file, child column(s), parent file, parent column(s))
RELATIONSHIPS: list[tuple[str, list[str], str, list[str]]] = [
    ("olist_orders_dataset.csv", ["customer_id"],
     "olist_customers_dataset.csv", ["customer_id"]),
    ("olist_order_items_dataset.csv", ["order_id"],
     "olist_orders_dataset.csv", ["order_id"]),
    ("olist_order_items_dataset.csv", ["product_id"],
     "olist_products_dataset.csv", ["product_id"]),
    ("olist_order_items_dataset.csv", ["seller_id"],
     "olist_sellers_dataset.csv", ["seller_id"]),
    ("olist_order_payments_dataset.csv", ["order_id"],
     "olist_orders_dataset.csv", ["order_id"]),
    ("olist_order_reviews_dataset.csv", ["order_id"],
     "olist_orders_dataset.csv", ["order_id"]),
    ("olist_products_dataset.csv", ["product_category_name"],
     "product_category_name_translation.csv", ["product_category_name"]),
]

# Candidate keys to verify (single-column and composite).
CANDIDATE_KEYS: dict[str, list[list[str]]] = {
    "olist_customers_dataset.csv": [["customer_id"], ["customer_unique_id"]],
    "olist_orders_dataset.csv": [["order_id"]],
    "olist_order_items_dataset.csv": [["order_id", "order_item_id"]],
    "olist_order_payments_dataset.csv": [["order_id", "payment_sequential"]],
    "olist_order_reviews_dataset.csv": [["review_id"]],
    "olist_products_dataset.csv": [["product_id"]],
    "olist_sellers_dataset.csv": [["seller_id"]],
    "product_category_name_translation.csv": [["product_category_name"]],
}


@dataclass
class TableProfile:
    name: str
    frame: pd.DataFrame = field(repr=False)
    duplicate_rows: int = 0

    @property
    def n_rows(self) -> int:
        return len(self.frame)


def load_all() -> dict[str, TableProfile]:
    profiles: dict[str, TableProfile] = {}
    for filename in CSV_FILES:
        path = DATA_DIR / filename
        if not path.exists():
            raise FileNotFoundError(f"Missing source file: {path}")
        df = pd.read_csv(path)
        profiles[filename] = TableProfile(
            name=filename, frame=df, duplicate_rows=int(df.duplicated().sum())
        )
    return profiles


def key_is_unique(df: pd.DataFrame, cols: list[str]) -> bool:
    return not df.duplicated(subset=cols).any()


def orphan_count(
    child: pd.DataFrame, child_cols: list[str],
    parent: pd.DataFrame, parent_cols: list[str],
) -> int:
    """Rows in child whose key does not exist in parent (NULL keys excluded)."""
    c = child[child_cols].dropna()
    p = parent[parent_cols].dropna().drop_duplicates()
    merged = c.merge(p, left_on=child_cols, right_on=parent_cols, how="left", indicator=True)
    return int((merged["_merge"] == "left_only").sum())


def column_table(df: pd.DataFrame) -> list[str]:
    lines = [
        "| Column | Inferred dtype | Nulls | Distinct | All unique | Example |",
        "|---|---|---:|---:|---|---|",
    ]
    for col in df.columns:
        s = df[col]
        example = str(s.dropna().iloc[0]) if s.notna().any() else ""
        if len(example) > 40:
            example = example[:37] + "..."
        example = example.replace("|", "\\|")
        lines.append(
            f"| `{col}` | {s.dtype} | {int(s.isna().sum())} | {s.nunique()} "
            f"| {'yes' if key_is_unique(df, [col]) else 'no'} | {example} |"
        )
    return lines


def build_report(profiles: dict[str, TableProfile]) -> str:
    lines: list[str] = [
        "# Olist Dataset — Data Inspection Report",
        "",
        "Generated by `python -m scripts.inspect_data` from the raw CSVs in `data/`.",
        "Source: Brazilian E-Commerce Public Dataset by Olist (Kaggle).",
        "",
        "## 1. Overview",
        "",
        "| File | Rows | Columns | Duplicate rows | Cells missing |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, prof in profiles.items():
        df = prof.frame
        lines.append(
            f"| `{name}` | {prof.n_rows} | {df.shape[1]} | {prof.duplicate_rows} "
            f"| {int(df.isna().sum().sum())} |"
        )

    lines += ["", "## 2. Candidate primary keys", "",
              "| File | Candidate key | Unique? |", "|---|---|---|"]
    for name, candidates in CANDIDATE_KEYS.items():
        df = profiles[name].frame
        for cols in candidates:
            unique = key_is_unique(df, cols)
            lines.append(f"| `{name}` | `{' + '.join(cols)}` | {'YES' if unique else 'NO'} |")

    lines += ["", "## 3. Relationship checks (anti-join orphan counts)", "",
              "| Child | Parent | Orphan rows | Verdict |", "|---|---|---:|---|"]
    for child_name, child_cols, parent_name, parent_cols in RELATIONSHIPS:
        n = orphan_count(
            profiles[child_name].frame, child_cols,
            profiles[parent_name].frame, parent_cols,
        )
        verdict = "OK — FK safe" if n == 0 else f"{n} orphans — investigate"
        lines.append(
            f"| `{child_name}` ({', '.join(child_cols)}) "
            f"| `{parent_name}` ({', '.join(parent_cols)}) | {n} | {verdict} |"
        )

    lines += ["", "## 4. Per-table detail", ""]
    for name, prof in profiles.items():
        lines += [f"### `{name}`", ""]
        lines += column_table(prof.frame)
        lines.append("")

    # Extra facts that drive schema design.
    orders = profiles["olist_orders_dataset.csv"].frame
    customers = profiles["olist_customers_dataset.csv"].frame
    lines += [
        "## 5. Observations for schema design",
        "",
        f"- `orders.order_status` values: {sorted(orders['order_status'].unique().tolist())}.",
        f"- `orders.order_purchase_timestamp` range: {orders['order_purchase_timestamp'].min()} "
        f"to {orders['order_purchase_timestamp'].max()}.",
        f"- `customers.customer_id` is unique per row ({customers['customer_id'].nunique()} values) "
        f"but `customer_unique_id` has {customers['customer_unique_id'].nunique()} distinct values "
        f"across {len(customers)} rows — customer_id identifies an order-side customer record, "
        "customer_unique_id identifies the actual customer.",
        "- Timestamp columns are read as text by pandas; they map to PostgreSQL `timestamp`.",
        "- ID columns are 32-char hex strings; they map to `varchar(32)` (or `text`).",
        "- `order_items` price/freight and `payments.payment_value` are monetary → `numeric(10,2)`.",
        "- Geolocation has no primary key and contains duplicate rows; it is a lookup, not an entity.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    profiles = load_all()
    report = build_report(profiles)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report, encoding="utf-8")

    print(f"Inspected {len(profiles)} files. Report: {REPORT_PATH}")
    for name, prof in profiles.items():
        print(f"  {name}: {prof.n_rows} rows, {prof.frame.shape[1]} cols, "
              f"{prof.duplicate_rows} duplicate rows")


if __name__ == "__main__":
    main()